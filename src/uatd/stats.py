"""Dataset analysis (roadmap step 3) and the frozen tiny-object threshold.

    python -m uatd.stats --coco-dir data/processed/coco --out results/dataset_stats \\
        --write-eval-config configs/eval.yaml

Reads the cleaned COCO views written by ``uatd.convert`` (real image sizes, cleaned
boxes) and writes to ``--out``:

* ``summary.json``: per split, image sizes, objects per image, box width / height /
  area / aspect-ratio percentiles overall and per class, relative box area, and box
  size after resizing the image to common square model inputs (RF-DETR stretches the
  image to a square, so a box shrinks by ``res/W`` horizontally and ``res/H`` vertically).
* ``*.png`` figures (box-area histograms, per-class box areas, image sizes, objects per
  image).

``--write-eval-config`` freezes the UATD-relative size bins (CLAUDE.md, Section 6):
``tiny`` = box area <= the 25th percentile of **train** box areas (absolute pixels).
The file is never overwritten once it exists (use a new file to change the definition).
"""

from __future__ import annotations

import argparse
import json
import os
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np

SPLITS = ("train", "val", "test1", "test2")
PCTS = (0, 5, 25, 50, 75, 95, 100)
MODEL_RES = (384, 512, 576, 640, 1024)
TINY_PERCENTILE = 25


def _pct(values) -> dict:
    v = np.asarray(values, dtype=float)
    if v.size == 0:
        return {}
    out = {f"p{p}": float(np.percentile(v, p)) for p in PCTS}
    out["mean"] = float(v.mean())
    out["n"] = int(v.size)
    return out


def load(coco_dir: Path, split: str) -> dict:
    return json.loads((coco_dir / f"{split}.json").read_text(encoding="utf-8"))


def split_stats(coco: dict) -> dict:
    names = {c["id"]: c["name"] for c in coco["categories"]}
    imgs = {i["id"]: i for i in coco["images"]}
    per_img = Counter(a["image_id"] for a in coco["annotations"])
    sizes = Counter(f"{i['width']}x{i['height']}" for i in coco["images"])

    w, h, area, rel, ar = [], [], [], [], []
    by_cls: dict[str, dict[str, list]] = defaultdict(lambda: defaultdict(list))
    resized: dict[int, dict[str, list]] = {r: {"w": [], "h": [], "area": []} for r in MODEL_RES}
    for a in coco["annotations"]:
        im = imgs[a["image_id"]]
        bw, bh = a["bbox"][2], a["bbox"][3]
        w.append(bw)
        h.append(bh)
        area.append(bw * bh)
        rel.append(bw * bh / (im["width"] * im["height"]))
        ar.append(bw / bh)
        c = by_cls[names[a["category_id"]]]
        c["w"].append(bw)
        c["h"].append(bh)
        c["area"].append(bw * bh)
        for r in MODEL_RES:
            rw, rh = bw * r / im["width"], bh * r / im["height"]
            resized[r]["w"].append(rw)
            resized[r]["h"].append(rh)
            resized[r]["area"].append(rw * rh)

    return {
        "images": len(coco["images"]),
        "objects": len(coco["annotations"]),
        "image_width": _pct([i["width"] for i in coco["images"]]),
        "image_height": _pct([i["height"] for i in coco["images"]]),
        "image_sizes_top10": dict(sizes.most_common(10)),
        "num_distinct_image_sizes": len(sizes),
        "objects_per_image": {
            **_pct([per_img.get(i, 0) for i in imgs]),
            "histogram": dict(sorted(Counter(per_img.get(i, 0) for i in imgs).items())),
        },
        "box_width": _pct(w),
        "box_height": _pct(h),
        "box_area": _pct(area),
        "box_relative_area": _pct(rel),
        "box_aspect_w_over_h": _pct(ar),
        "per_class": {
            n: {"objects": len(v["area"]), **{k: _pct(v[k]) for k in ("w", "h", "area")}}
            for n, v in sorted(by_cls.items(), key=lambda kv: list(names.values()).index(kv[0]))
        },
        "after_square_resize": {
            str(r): {k: _pct(v) for k, v in d.items()} for r, d in resized.items()
        },
    }


def tiny_threshold(train_coco: dict, percentile: float = TINY_PERCENTILE) -> float:
    areas = [a["bbox"][2] * a["bbox"][3] for a in train_coco["annotations"]]
    return float(np.percentile(areas, percentile))


def size_bins(threshold: float) -> dict[str, list[float]]:
    """pycocotools areaRng is inclusive at both ends: tiny = [0, t], rest strictly above t."""
    return {"tiny": [0.0, threshold], "non_tiny": [float(np.nextafter(threshold, np.inf)), 1e10]}


def write_eval_config(path: Path, threshold: float, train_stats: dict) -> None:
    if path.exists():
        raise FileExistsError(f"{path} is frozen; not overwriting (CLAUDE.md, Section 6)")
    bins = size_bins(threshold)
    side = threshold**0.5
    text = (
        "# Frozen UATD-relative size bins (CLAUDE.md Section 6).\n"
        "# Generated by uatd.stats; do not edit.\n"
        f"# tiny = box area <= {TINY_PERCENTILE}th percentile of TRAIN box areas (cleaned boxes,\n"
        f"# original image pixels): {threshold:.1f} px^2 (about {side:.1f} x {side:.1f} px).\n"
        f"# Train box area percentiles: p5 {train_stats['box_area']['p5']:.0f}, "
        f"p50 {train_stats['box_area']['p50']:.0f}, "
        f"p95 {train_stats['box_area']['p95']:.0f} px^2.\n"
        "# COCO's absolute bins (small < 32^2, medium < 96^2, large) are reported as well.\n"
        f"tiny_percentile: {TINY_PERCENTILE}\n"
        f"tiny_area_threshold_px2: {threshold}\n"
        "size_bins:\n"
        f"  tiny: [{bins['tiny'][0]}, {bins['tiny'][1]}]\n"
        f"  non_tiny: [{bins['non_tiny'][0]}, {bins['non_tiny'][1]}]\n"
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def make_figures(cocos: dict[str, dict], threshold: float, out: Path) -> list[Path]:
    os.environ.setdefault("MPLBACKEND", "Agg")
    import matplotlib.pyplot as plt

    files = []
    names = [c["name"] for c in cocos["train"]["categories"]]

    fig, ax = plt.subplots(figsize=(7, 4))
    bins = np.logspace(1, 6, 60)
    for s, coco in cocos.items():
        areas = [a["bbox"][2] * a["bbox"][3] for a in coco["annotations"]]
        ax.hist(areas, bins=bins, histtype="step", density=True, label=s, linewidth=1.5)
    ax.axvline(threshold, color="k", ls="--", lw=1, label=f"tiny <= {threshold:.0f} px²")
    for v, lbl in ((32**2, "COCO 32²"), (96**2, "COCO 96²")):
        ax.axvline(v, color="grey", ls=":", lw=1)
        ax.text(v, ax.get_ylim()[1] * 0.9, lbl, rotation=90, va="top", ha="right", fontsize=8)
    ax.set_xscale("log")
    ax.set_xlabel("box area (px², original image)")
    ax.set_ylabel("density")
    ax.legend(fontsize=8)
    ax.set_title("UATD box areas by split")
    files.append(out / "box_area_by_split.png")
    fig.tight_layout()
    fig.savefig(files[-1], dpi=150)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(8, 4))
    data = [
        [
            a["bbox"][2] * a["bbox"][3]
            for a in cocos["train"]["annotations"]
            if a["category_id"] == i
        ]
        for i in range(len(names))
    ]
    ax.boxplot(data, showfliers=False)
    ax.set_xticks(range(1, len(names) + 1), names, rotation=35, ha="right")
    ax.axhline(threshold, color="k", ls="--", lw=1, label="tiny threshold")
    ax.set_yscale("log")
    ax.set_ylabel("box area (px²)")
    ax.set_title("Train box area per class (whiskers 1.5 IQR, no outliers)")
    ax.legend(fontsize=8)
    files.append(out / "box_area_per_class_train.png")
    fig.tight_layout()
    fig.savefig(files[-1], dpi=150)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(6, 4))
    for s, coco in cocos.items():
        sz = Counter((i["width"], i["height"]) for i in coco["images"])
        xs, ys, n = zip(*[(w, h, c) for (w, h), c in sz.items()], strict=True)
        ax.scatter(xs, ys, s=[8 + 2 * c**0.5 for c in n], alpha=0.5, label=s)
    ax.set_xlabel("image width (px)")
    ax.set_ylabel("image height (px)")
    ax.set_title("Native image sizes (marker size ~ count)")
    ax.legend(fontsize=8)
    files.append(out / "image_sizes.png")
    fig.tight_layout()
    fig.savefig(files[-1], dpi=150)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(6, 4))
    width = 0.2
    for k, (s, coco) in enumerate(cocos.items()):
        per = Counter(a["image_id"] for a in coco["annotations"])
        hist = Counter(per.get(i["id"], 0) for i in coco["images"])
        xs = sorted(hist)
        ax.bar(
            [x + (k - 1.5) * width for x in xs],
            [hist[x] / len(coco["images"]) for x in xs],
            width,
            label=s,
        )
    ax.set_xlabel("objects per image")
    ax.set_ylabel("fraction of images")
    ax.set_title("Objects per image")
    ax.legend(fontsize=8)
    files.append(out / "objects_per_image.png")
    fig.tight_layout()
    fig.savefig(files[-1], dpi=150)
    plt.close(fig)
    return files


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--coco-dir", type=Path, default=Path("data/processed/coco"))
    ap.add_argument("--out", type=Path, default=Path("results/dataset_stats"))
    ap.add_argument("--write-eval-config", type=Path, help="freeze size bins here (once)")
    ap.add_argument("--no-figures", action="store_true")
    args = ap.parse_args(argv)

    cocos = {s: load(args.coco_dir, s) for s in SPLITS}
    stats = {s: split_stats(c) for s, c in cocos.items()}
    thr = tiny_threshold(cocos["train"])
    stats["tiny_definition"] = {
        "percentile_of_train_box_area": TINY_PERCENTILE,
        "threshold_px2": thr,
        "threshold_side_px": thr**0.5,
        "fraction_tiny_per_split": {
            s: float(np.mean([a["bbox"][2] * a["bbox"][3] <= thr for a in c["annotations"]]))
            for s, c in cocos.items()
        },
        "coco_bins_fraction_per_split": {
            s: {
                "small(<32^2)": float(np.mean([a["area"] < 32**2 for a in c["annotations"]])),
                "medium": float(np.mean([32**2 <= a["area"] < 96**2 for a in c["annotations"]])),
                "large(>=96^2)": float(np.mean([a["area"] >= 96**2 for a in c["annotations"]])),
            }
            for s, c in cocos.items()
        },
    }
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "summary.json").write_text(
        json.dumps(stats, indent=2) + "\n", encoding="utf-8", newline="\n"
    )
    if not args.no_figures:
        for f in make_figures(cocos, thr, args.out):
            print("wrote", f)
    if args.write_eval_config:
        write_eval_config(args.write_eval_config, thr, stats["train"])
        print("froze size bins in", args.write_eval_config)

    t = stats["tiny_definition"]
    print(f"tiny threshold: {thr:.1f} px^2 (~{t['threshold_side_px']:.1f} px side)")
    for s in SPLITS:
        st = stats[s]
        print(
            f"{s:6s} imgs {st['images']:5d} objs {st['objects']:6d}  "
            f"img WxH median {st['image_width']['p50']:.0f}x{st['image_height']['p50']:.0f}  "
            f"box area p25/p50/p75 {st['box_area']['p25']:.0f}/{st['box_area']['p50']:.0f}/"
            f"{st['box_area']['p75']:.0f}  tiny {t['fraction_tiny_per_split'][s]:.1%}"
        )


if __name__ == "__main__":
    main()
